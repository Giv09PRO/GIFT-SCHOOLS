    /**
     * Show the form for editing the specified report card.
     *
     * @param ReportCard $reportcard
     * @return View
     * @throws AuthorizationException
     */
    public function edit(ReportCard $reportcard): View
    {
        $this->authorize('edit report_cards', $reportcard);
        $reportcard->load(['student', 'markingPeriod', 'gradeLevel']);

        $currentSchoolId = $reportcard->school_id;
        $currentSyear = $reportcard->syear;

        // Students list should be relevant to the report card's context
        $students = Student::query()->select('students.id', 'students.first_name', 'students.middle_name', 'students.last_name', 'students.username')
            ->join('student_enrollment', 'students.id', '=', 'student_enrollment.student_id')
            ->where('student_enrollment.school_id', $currentSchoolId)
            ->where('student_enrollment.syear', $currentSyear)
            ->where('student_enrollment.start_date', '<=', now())
            ->where(function ($q) {
                $q->where('student_enrollment.end_date', '>=', now())->orWhereNull('student_enrollment.end_date');
            })
            ->distinct()->orderBy('students.last_name')->orderBy('students.first_name')->get()
            ->mapWithKeys(function($student){
                $name = trim(($student->first_name ?? '') . ' ' . ($student->middle_name ?? '') . ' ' . ($student->last_name ?? ''));
                return [$student->id => $name . ' (' . ($student->username ?? 'N/A') . ')'];
            });

        $markingPeriods = SchoolMarkingPeriod::where('school_id', $currentSchoolId)->where('syear', $currentSyear)->orderBy('title')->pluck('title', 'marking_period_id');
        $gradeLevels = GradeLevel::where('school_id', $currentSchoolId)->where('school_syear', $currentSyear)->orderBy('title')->pluck('title', 'id');

        // Prepare subject_grades for form display if it's structured
        $subject_grades_structured = is_string($reportcard->subject_grades) ? json_decode($reportcard->subject_grades, true) : $reportcard->subject_grades;
        if (json_last_error() !== JSON_ERROR_NONE) {
            $subject_grades_structured = []; // Default to empty array if JSON is invalid
        }


        return view('pages.staff.reportcards.edit', compact('reportcard', 'students', 'markingPeriods', 'gradeLevels', 'subject_grades_structured'));
    }

    /**
     * Update the specified report card in storage.
     *
     * @param Request $request
     * @param ReportCard $reportcard
     * @return RedirectResponse
     * @throws AuthorizationException
     * @throws ValidationException
     */
    public function update(Request $request, ReportCard $reportcard): RedirectResponse
    {
        $this->authorize('edit report_cards', $reportcard);

        $validatedData = $request->validate([
            'student_id' => ['required', 'exists:students,id',
                Rule::unique('report_cards')->where(function ($query) use ($request, $reportcard) {
                    return $query->where('student_id', $request->student_id)
                        ->where('marking_period_id', $request->marking_period_id)
                        ->where('syear', $reportcard->syear)
                        ->where('school_id', $reportcard->school_id);
                })->ignore($reportcard->id)
            ],
            'marking_period_id' => 'required|exists:school_marking_periods,marking_period_id',
            'grade_id' => 'nullable|exists:school_gradelevels,id',
            'subject_grades_structured' => 'nullable|array',
            'subject_grades_structured.*.subject_id' => 'required_with:subject_grades_structured|exists:subjects,subject_id',
            'subject_grades_structured.*.grade' => 'nullable|string|max:10',
            'subject_grades_structured.*.comment' => 'nullable|string|max:255',
            'subject_grades' => 'nullable|json',
            'comments' => 'nullable|string',
            'is_published' => 'required|boolean',
        ]);

        return DB::transaction(function () use ($validatedData, $request, $reportcard) {
            $updateData = $validatedData;

            if (!empty($validatedData['subject_grades_structured'])) {
                $updateData['subject_grades'] = json_encode($validatedData['subject_grades_structured']);
            } elseif (isset($validatedData['subject_grades'])) { // Check if raw JSON was passed and validated
                $updateData['subject_grades'] = $validatedData['subject_grades'];
            } else {
                // If neither structured nor raw JSON is provided, but you want to clear existing, set to null
                // $updateData['subject_grades'] = null;
                // Or, if you want to preserve existing if nothing new is sent, remove it from $updateData
                unset($updateData['subject_grades']);
            }
            unset($updateData['subject_grades_structured']);


            $reportcard->update($updateData);
            Log::info('Report Card updated.', ['id' => $reportcard->id, 'user_id' => Auth::guard('staff')->id()]);
            return redirect()->route('staff.reportcards.index')->with('success', 'Report Card updated successfully.');
        });
    }

    /**
     * Remove the specified report card from storage.
     *
     * @param ReportCard $reportcard
     * @return JsonResponse|RedirectResponse
     * @throws AuthorizationException
     */
    public function destroy(ReportCard $reportcard): JsonResponse|RedirectResponse
    {
        $this->authorize('delete report_cards', $reportcard);

        return DB::transaction(function () use ($reportcard) {
            $reportcard->delete();
            Log::info('Report Card deleted.', ['id' => $reportcard->id, 'user_id' => Auth::guard('staff')->id()]);

            if (request()->ajax()) {
                return response()->json(['success' => true, 'message' => 'Report Card deleted successfully.']);
            }
            return redirect()->route('staff.reportcards.index')->with('success', 'Report Card deleted successfully.');
        });
    }

    /**
     * Toggle the publish status of a report card.
     *
     * @param ReportCard $reportcard
     * @return RedirectResponse
     * @throws AuthorizationException
     */
    public function togglePublish(ReportCard $reportcard): RedirectResponse
    {
        $this->authorize('publish report_cards', $reportcard);

        return DB::transaction(function () use ($reportcard) {
            $reportcard->is_published = !$reportcard->is_published;
            $reportcard->save();
            $statusMessage = $reportcard->is_published ? 'published' : 'unpublished';
            Log::info('Report Card publish status toggled.', ['id' => $reportcard->id, 'published' => $reportcard->is_published, 'user_id' => Auth::guard('staff')->id()]);
            return redirect()->back()->with('success', "Report Card successfully {$statusMessage}.");
        });
    }
