    /**
     * Display a listing of the report cards.
     *
     * @param Request $request
     * @return View
     * @throws AuthorizationException
     */
    public function index(Request $request): View
    {
        $this->authorize('view report_cards');

        $currentSchoolId = session('current_school_id');
        $currentSyear = session('current_syear', date('Y'));

        // Fallback if session variables are not set (though ideally, they should be guaranteed by middleware or earlier logic)
        if (!$currentSchoolId || !$currentSyear) {
            Log::warning('Current school ID or syear not found in session for ReportCard index.', ['user_id' => Auth::id()]);
            // Redirect or show an error, or fetch all if that's desired (though risky)
            // For now, we'll proceed, but queries might return empty or all data if not filtered.
            // It's better to enforce these session variables.
        }

        $query = ReportCard::query()
            ->with(['student', 'markingPeriod', 'gradeLevel', 'school', 'generator'])
            ->where('school_id', $currentSchoolId)
            ->where('syear', $currentSyear);

        // --- Apply Filters ---
        if ($request->filled('student_search_term')) {
            $searchTerm = '%' . $request->student_search_term . '%';
            $query->whereHas('student', function ($q) use ($searchTerm) {
                $q->where(DB::raw("CONCAT(COALESCE(first_name,''), ' ', COALESCE(middle_name,''), ' ', COALESCE(last_name,''))"), 'LIKE', $searchTerm)
                    ->orWhere('username', 'LIKE', $searchTerm);
            });
        }
        if ($request->filled('marking_period_id_filter')) {
            $query->where('marking_period_id', $request->marking_period_id_filter);
        }
        if ($request->filled('grade_id_filter')) {
            $query->where('grade_id', $request->grade_id_filter);
        }
        if ($request->filled('is_published_filter')) {
            $query->where('is_published', $request->is_published_filter === '1');
        }

        // --- Initial Sorting ---
        $sortBy = $request->input('sort_by', 'created_at');
        $sortOrder = $request->input('sort_order', 'desc');
        $allowedSorts = ['student_id', 'marking_period_id', 'grade_id', 'is_published', 'created_at'];

        if (in_array($sortBy, $allowedSorts)) {
            $query->orderBy($sortBy, $sortOrder);
        } else {
            $query->orderBy('created_at', 'desc');
        }

        $reportCards = $query->get();
        $currentUser = Auth::guard('staff')->user(); // Use staff guard

        // 1. Define Headers for AdminLTE Datatable
        $heads = [
            'ID', 'Student', 'Marking Period', 'Grade Level',
            ['label' => 'Published', 'width' => 8, 'class' => 'text-center'],
            'Generated By', 'Created At',
            ['label' => 'Actions', 'no-export' => true, 'width' => 15, 'orderable' => false, 'class' => 'text-center'],
        ];

        // 2. Build the data array for AdminLTE Datatable
        $data = [];
        foreach ($reportCards as $reportCard) {
            $studentName = $reportCard->student ? e(trim(($reportCard->student->first_name ?? '') . ' ' . ($reportCard->student->middle_name ?? '') . ' ' . ($reportCard->student->last_name ?? ''))) : 'N/A';
            $studentUsername = $reportCard->student ? e($reportCard->student->username) : '';
            $studentHtml = "N/A";
            if ($reportCard->student && $reportCard->student_id) {
                $studentShowRoute = route('staff.students.show', $reportCard->student_id);
                $studentHtml = "<a href='{$studentShowRoute}'>{$studentName}</a><small class='d-block text-muted'>{$studentUsername}</small>";
            } elseif($reportCard->student) {
                $studentHtml = "{$studentName}<small class='d-block text-muted'>{$studentUsername}</small>";
            }

            $markingPeriodTitle = $reportCard->markingPeriod ? e($reportCard->markingPeriod->title) : 'N/A';
            $gradeLevelTitle = $reportCard->gradeLevel ? e($reportCard->gradeLevel->title) : 'N/A';
            $generatorName = $reportCard->generator ? e(trim(($reportCard->generator->first_name ?? '') . ' ' . ($reportCard->generator->last_name ?? ''))) : 'N/A';
            $publishedHtml = $reportCard->is_published ? '<span class="badge badge-success">Yes</span>' : '<span class="badge badge-warning">No</span>';

            $actionsHtml = "<nobr>";
            if ($currentUser && $currentUser->can('show report_cards', $reportCard)) {
                $actionsHtml .= "<a href='" . route('staff.reportcards.show', $reportCard->id) . "' class='btn btn-xs btn-info mr-1' title='View Report Card'><i class='fa fa-eye'></i></a>";
            }
            if ($currentUser && $currentUser->can('edit report_cards', $reportCard)) {
                $actionsHtml .= "<a href='" . route('staff.reportcards.edit', $reportCard->id) . "' class='btn btn-xs btn-primary mr-1' title='Edit Report Card'><i class='fa fa-edit'></i></a>";
            }
            if ($currentUser && $currentUser->can('publish report_cards', $reportCard)) {
                $publishRoute = route('staff.reportcards.togglePublish', $reportCard->id);
                $publishIcon = $reportCard->is_published ? 'fa-toggle-off' : 'fa-toggle-on';
                $publishTitle = $reportCard->is_published ? 'Unpublish' : 'Publish';
                $publishBtnClass = $reportCard->is_published ? 'btn-warning' : 'btn-success';
                $actionsHtml .= "<form action='{$publishRoute}' method='POST' class='d-inline m-0 p-0' onsubmit='return confirm(\"Are you sure you want to " . strtolower($publishTitle) . " this report card?\");'>".csrf_field().method_field('PATCH')."<button type='submit' class='btn btn-xs {$publishBtnClass} mr-1' title='{$publishTitle}'><i class='fas {$publishIcon}'></i></button></form>";
            }
            if ($currentUser && $currentUser->can('delete report_cards', $reportCard)) {
                $actionsHtml .= "<button type='button' class='btn btn-xs btn-danger delete-reportcard-btn' data-id='{$reportCard->id}' title='Delete Report Card'><i class='fa fa-trash'></i></button>";
            }
            $actionsHtml .= "</nobr>";

            $data[] = [
                $reportCard->id, $studentHtml, $markingPeriodTitle, $gradeLevelTitle,
                $publishedHtml, $generatorName,
                $reportCard->created_at ? $reportCard->created_at->format('Y-m-d H:i') : 'N/A',
                $actionsHtml,
            ];
        }

        $config = [ /* ... (config array remains the same) ... */
            'data' => $data,
            'order' => [[6, 'desc']],
            'columns' => [
                null, null, null, null,
                ['className' => 'text-center'],
                null, null,
                ['orderable' => false, 'searchable' => false, 'className' => 'text-center'],
            ],
            'paging' => true, 'lengthChange' => true, 'lengthMenu' => [10, 25, 50, 100, 250],
            'searching' => true, 'info' => true, 'responsive' => true, 'autoWidth' => false,
        ];

        Log::info('ReportCard index viewed', ['user_id' => Auth::guard('staff')->id(), 'filters' => $request->all(), 'result_count' => count($data)]);

        $markingPeriodsForFilter = SchoolMarkingPeriod::where('school_id', $currentSchoolId)->where('syear', $currentSyear)->orderBy('title')->pluck('title', 'marking_period_id');
