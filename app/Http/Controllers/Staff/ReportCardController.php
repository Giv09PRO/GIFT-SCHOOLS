        $publishStatuses = ['' => 'All Statuses', '1' => 'Published', '0' => 'Not Published'];

        return view('pages.staff.reports.index', compact( // Corrected view path
            'heads', 'config', 'reportCards',
            'markingPeriodsForFilter', 'gradeLevelsForFilter', 'publishStatuses',
            'currentSchoolId', 'currentSyear'
        ));
    }

    /**
     * Show the form for creating a new report card.
     *
     * @param Request $request
     * @return View
     * @throws AuthorizationException
     */
    public function create(Request $request): View|RedirectResponse
    {
        $this->authorize('create report_cards');

        $currentSchoolId = session('current_school_id');
        $currentSyear = session('current_syear', date('Y'));

        if (!$currentSchoolId || !$currentSyear) {
            return redirect()->route('staff.dashboard') // Or a more appropriate error page
            ->with('error', 'Current school or academic year not set. Please select them first.');
        }

        $studentsQuery = Student::query()->select('students.id', 'students.first_name', 'students.middle_name', 'students.last_name', 'students.username')
            ->join('student_enrollment', 'students.id', '=', 'student_enrollment.student_id')
            ->where('student_enrollment.school_id', $currentSchoolId)
            ->where('student_enrollment.syear', $currentSyear)
            ->where('student_enrollment.start_date', '<=', now())
            ->where(function ($q) {
                $q->where('student_enrollment.end_date', '>=', now())
                    ->orWhereNull('student_enrollment.end_date');
            });

        if ($request->has('grade_id_filter_form')) { // Use a distinct name for form filter
            $studentsQuery->where('student_enrollment.grade_id', $request->grade_id_filter_form);
        }

        $students = $studentsQuery->distinct()->orderBy('students.last_name')->orderBy('students.first_name')->get()
            ->mapWithKeys(function($student){
                $name = trim(($student->first_name ?? '') . ' ' . ($student->middle_name ?? '') . ' ' . ($student->last_name ?? ''));
                return [$student->id => $name . ' (' . ($student->username ?? 'N/A') . ')'];
            });

        $markingPeriods = SchoolMarkingPeriod::where('school_id', $currentSchoolId)->where('syear', $currentSyear)->orderBy('title')->pluck('title', 'marking_period_id');
        $gradeLevels = GradeLevel::where('school_id', $currentSchoolId)->where('school_syear', $currentSyear)->orderBy('title')->pluck('title', 'id');

        return view('pages.staff.reportcards.create', compact('students', 'markingPeriods', 'gradeLevels', 'currentSchoolId', 'currentSyear'));
    }

    /**
     * Store a newly created report card in storage.
     *
     * @param Request $request
     * @return RedirectResponse
     * @throws AuthorizationException
     * @throws ValidationException
     */
    public function store(Request $request): RedirectResponse
    {
        $this->authorize('create report_cards');

        $validatedData = $request->validate([
            'syear' => 'required|numeric|digits:4',
            'school_id' => 'required|exists:schools,id',
            'student_id' => ['required', 'exists:students,id',
                Rule::unique('report_cards')->where(function ($query) use ($request) {
                    return $query->where('student_id', $request->student_id)
                        ->where('marking_period_id', $request->marking_period_id)
                        ->where('syear', $request->syear)
                        ->where('school_id', $request->school_id);
                })
            ],
            'marking_period_id' => 'required|exists:school_marking_periods,marking_period_id',
            'grade_id' => 'nullable|exists:school_gradelevels,id',
            'subject_grades_structured' => 'nullable|array', // Expect an array for structured input
            'subject_grades_structured.*.subject_id' => 'required_with:subject_grades_structured|exists:subjects,subject_id',
            'subject_grades_structured.*.grade' => 'nullable|string|max:10', // Example validation
            'subject_grades_structured.*.comment' => 'nullable|string|max:255', // Example validation
            'subject_grades' => 'nullable|json', // Allow raw JSON input as fallback
            'comments' => 'nullable|string',
            'is_published' => 'required|boolean',
        ]);

        return DB::transaction(function () use ($validatedData, $request) {
            $reportCardData = $validatedData;
            $reportCardData['generated_by'] = Auth::guard('staff')->id();

            // Handle subject_grades: prioritize structured input
            if (!empty($validatedData['subject_grades_structured'])) {
                $reportCardData['subject_grades'] = json_encode($validatedData['subject_grades_structured']);
            } elseif (!empty($validatedData['subject_grades'])) {
                // If raw JSON is provided and validated, use it.
                // The 'json' rule already validated it.
                $reportCardData['subject_grades'] = $validatedData['subject_grades'];
            } else {
                $reportCardData['subject_grades'] = null; // Ensure it's null if neither is provided
            }
            unset($reportCardData['subject_grades_structured']); // Don't try to save this to DB

            $reportCard = ReportCard::create($reportCardData);
            Log::info('Report Card created.', ['id' => $reportCard->id, 'user_id' => Auth::guard('staff')->id()]);
            return redirect()->route('staff.reportcards.index')->with('success', 'Report Card created successfully.');
        });
    }

